/**
 * Extracts the two candidate records the PUBLIC demo screens render.
 *
 * /ai-pipeline and /whatsapp-demo are marketing simulations reachable
 * without signing in (they sit in the public nav as "AI Hiring Demo" and
 * "AI WhatsApp Agent"). They reference cand5 and cand4 by id.
 *
 * With real security in place an anonymous visitor cannot see any
 * candidate — correctly — so those pages would crash. The answer is not to
 * weaken the policy: it is to give the demo screens demo data, which is
 * what they always were. These fixtures live in a static file, never in
 * the database, so they can never appear in Find Candidates, a dashboard
 * count, or anyone's pipeline.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const html = readFileSync('baseline/prototype.html', 'utf8');
const blocks = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]);
const src = blocks.find(b => /const DATA = \{\}/.test(b) && /DATA\.stageForCandidateJob/.test(b));
const sb = { window: {}, console }; sb.window.window = sb.window;
vm.createContext(sb);
vm.runInContext(src + ';globalThis.__D = DATA;', sb);
const D = sb.__D;

// The demo screens reference cand4 (WhatsApp) and cand5 (AI pipeline) by
// id, but they also render a candidate PICKER built from DATA.candidates.
// All ten seed candidates are therefore included, so the dropdown has the
// same options it always had. They remain demo fixtures in a static file —
// never database rows, never visible in Find Candidates or any dashboard.
const IDS = null;                        // null = every seed candidate
const out = {
  _note: 'Demo fixtures for the public AI Hiring Demo and WhatsApp Agent screens. '
       + 'Generated by tools/extract-demo-fixtures.mjs from the prototype seed. '
       + 'NOT database records and never shown as real candidates.',
  candidates: D.candidates
    .filter(c => !IDS || IDS.includes(c.id))
    .map(c => ({ ...c, isDemo: true })),
  transcripts: D.aiInterviewTranscripts || {},
  resumeBank: Object.fromEntries(
    Object.entries(D.resumeBank || {}).filter(([k]) => !IDS || IDS.includes(k))),
};

writeFileSync('web/demo-fixtures.json', JSON.stringify(out, null, 1));
console.log(`wrote web/demo-fixtures.json — ${out.candidates.length} demo candidates ` +
            `(${out.candidates.map(c => c.id).join(', ')})`);
